export function pickLang(argv = process.argv.slice(2), env = process.env) {
  const flag = argv.find((a) => a.startsWith("--lang="))?.slice(7).toLowerCase();
  const candidato = flag || env.AE_MCP_LANG || Intl.DateTimeFormat().resolvedOptions().locale || "";
  const base = candidato.toLowerCase().slice(0, 2);
  return LANGS.includes(base) ? base : "en";
}

export function makeT(lang) {
  const d = T[lang] || T.en;
  return (k, p = {}) => (d[k] ?? T.en[k] ?? k).replace(/\{(\w+)\}/g, (_, n) => String(p[n] ?? ""));
}
